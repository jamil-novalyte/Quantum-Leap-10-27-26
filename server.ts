import express from 'express';
import { GoogleGenAI, Type } from '@google/genai';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json({ limit: '50mb' }));

// Server-side GoogleGenAI initialization with required User-Agent telemetry
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

/**
 * 1. Text-To-Speech API (gemini-3.8-flash-tts / gemini-3.8-flash-lite-tts)
 */
app.post('/api/tts', async (req, res) => {
  try {
    const { text, voiceName = 'Kore', style = 'Clear, powerful, grounded masculine voice' } = req.body;

    if (!text || typeof text !== 'string') {
      return res.status(400).json({ error: 'Text prompt is required.' });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: text.slice(0, 4000), // Enforce token safety limit per chunk
              speechMetadata: { style },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (!base64Audio) {
      throw new Error('No audio data generated by TTS model.');
    }

    return res.json({
      audioBase64: base64Audio,
      mimeType: 'audio/wav',
    });
  } catch (err: any) {
    console.error('TTS API error:', err);
    return res.status(500).json({ error: err.message || 'Failed to generate speech.' });
  }
});

/**
 * 2. Audio Transcription API (gemini-3.5-transcribe)
 */
app.post('/api/transcribe', async (req, res) => {
  try {
    const { audioBase64, mimeType = 'audio/webm' } = req.body;

    if (!audioBase64) {
      return res.status(400).json({ error: 'Audio base64 data is required.' });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.5-transcribe',
      contents: {
        parts: [
          {
            inlineData: {
              mimeType,
              data: audioBase64,
            },
          },
          { text: 'Transcribe this voice journal accurately verbatim. Do not summarize, just output the spoken transcript.' },
        ],
      },
    });

    const transcript = response.text || '';
    return res.json({ transcript });
  } catch (err: any) {
    console.error('Transcribe API error:', err);
    return res.status(500).json({ error: err.message || 'Failed to transcribe audio.' });
  }
});

/**
 * 3. AI Journal Analysis & Grounded Growth Coaching (gemini-3.8-flash)
 */
app.post('/api/analyze-journal', async (req, res) => {
  try {
    const { transcript, currentStageName = 'Stage 1 — Life-Upgrade Fire' } = req.body;

    if (!transcript) {
      return res.status(400).json({ error: 'Transcript is required for analysis.' });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: `You are the Novalyte AI Founder Executive Coach & Grounded Reflection Partner.
Review the user's reflection transcript below (associated with ${currentStageName}).

Transcript:
"${transcript}"

Provide a grounded, constructive analysis. Extract concrete action items, practical mindset shifts, and realistic physical or craft adjustments.

Return valid JSON with this exact structure:
{
  "summary": "1-2 sentence core reflection summary",
  "keyTakeaways": ["takeaway 1", "takeaway 2"],
  "actionItems": ["actionable step 1", "actionable step 2"],
  "groundedPerspective": "A calm, reality-grounded encouraging perspective that reinforces practical action and clarity."
}`,
      config: {
        responseMimeType: 'application/json',
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            summary: { type: Type.STRING },
            keyTakeaways: {
              type: Type.ARRAY,
              items: { type: Type.STRING },
            },
            actionItems: {
              type: Type.ARRAY,
              items: { type: Type.STRING },
            },
            groundedPerspective: { type: Type.STRING },
          },
          required: ['summary', 'keyTakeaways', 'actionItems', 'groundedPerspective'],
        },
      },
    });

    const jsonText = response.text || '{}';
    const parsed = JSON.parse(jsonText);
    return res.json(parsed);
  } catch (err: any) {
    console.error('Journal Analysis error:', err);
    return res.status(500).json({ error: err.message || 'Failed to analyze journal.' });
  }
});

/**
 * 4. Lyria Focus Music Generation API (lyria-3-clip-preview)
 */
app.post('/api/music', async (req, res) => {
  try {
    const { prompt = 'Calm deep-focus ambient pad with warm synth textures for deep focus and executive mastery' } = req.body;

    const responseStream = await ai.models.generateContentStream({
      model: 'lyria-3-clip-preview',
      contents: prompt,
    });

    let audioBase64 = '';
    let mimeType = 'audio/wav';

    for await (const chunk of responseStream) {
      const parts = chunk.candidates?.[0]?.content?.parts;
      if (!parts) continue;
      for (const part of parts) {
        if (part.inlineData?.data) {
          if (!audioBase64 && part.inlineData.mimeType) {
            mimeType = part.inlineData.mimeType;
          }
          audioBase64 += part.inlineData.data;
        }
      }
    }

    if (!audioBase64) {
      throw new Error('No audio returned from Lyria model.');
    }

    return res.json({
      audioBase64,
      mimeType,
    });
  } catch (err: any) {
    console.error('Lyria Music generation error:', err);
    return res.status(500).json({ error: err.message || 'Failed to generate focus music.' });
  }
});

// Serve frontend assets in production or mount Vite middleware in development
if (process.env.NODE_ENV === 'production') {
  app.use(express.static(path.join(__dirname, 'dist')));
  app.get('*', (_req, res) => {
    res.sendFile(path.join(__dirname, 'dist', 'index.html'));
  });
} else {
  const { createServer: createViteServer } = await import('vite');
  const vite = await createViteServer({
    server: { middlewareMode: true },
    appType: 'custom',
  });
  app.use(vite.middlewares);
  app.use('*', async (req, res, next) => {
    const url = req.originalUrl;
    try {
      let template = await import('fs').then((fs) =>
        fs.readFileSync(path.join(__dirname, 'index.html'), 'utf-8')
      );
      template = await vite.transformIndexHtml(url, template);
      res.status(200).set({ 'Content-Type': 'text/html' }).end(template);
    } catch (e: any) {
      vite.ssrFixStacktrace(e);
      next(e);
    }
  });
}

app.listen(PORT, () => {
  console.log(`Novalyte AI Founder Server running on http://localhost:${PORT}`);
});
